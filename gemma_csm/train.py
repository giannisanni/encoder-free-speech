"""Train Gemma-CSM. M0a: --shard data/shards/ljspeech_50.pt

Run on substrate inside tmux:
  scripts/gpu-claim.sh
  .venv/bin/python -m gemma_csm.train --shard data/shards/ljspeech_50.pt \
      --steps 6000 --out checkpoints/m0a
  scripts/gpu-release.sh
"""
import argparse
import time
from pathlib import Path

import soundfile as sf
import torch
from torch.utils.data import DataLoader

from gemma_csm.codec import MimiCodec
from gemma_csm.config import GemmaCSMConfig
from gemma_csm.dataset import CodesDataset, collate
from gemma_csm.loader import load_gemma_csm

EVAL_SENTENCES = [
    # [0] is in the 50-clip M0a training set (memorization probe);
    # [1] and [2] are novel (generalization probes, expect garble at M0a).
    # "[lj]" prefix pins eval samples to the LJSpeech voice (speaker-id
    # conditioning convention) so clips stay comparable across runs.
    "[lj] Printing, in the only sense with which we are at present concerned, differs from most if not from all the arts and crafts represented in the Exhibition",
    "[lj] The quick brown fox jumps over the lazy dog.",
    "[lj] This voice was generated by a Gemma backbone.",
]


def save_samples(model, tok, codec, out_dir: Path, step: int):
    model.eval()
    out_dir.mkdir(parents=True, exist_ok=True)
    for i, s in enumerate(EVAL_SENTENCES):
        ids = torch.tensor([tok(s)["input_ids"]], device="cuda")
        codes = model.generate_codes(ids, max_frames=200)
        wav = codec.decode(codes)
        sf.write(out_dir / f"step{step:06d}_s{i}.wav", wav.float().numpy(), 24_000)
    model.train()


def trainable_state_dict(model):
    return {k: v for k, v in model.state_dict().items()
            if "lora" in k or not k.startswith("backbone.")}


def make_optimizer(model, lr: float, depth_lr_mult: float = 1.0):
    """AdamW with the depth decoder in its own (optionally hotter) param group.

    PersonaPlex trains its depth transformer at 2x the temporal transformer's
    LR; from-scratch depth params can absorb a hotter rate than LoRA adapters.
    """
    depth, rest = [], []
    for name, p in model.named_parameters():
        if not p.requires_grad:
            continue
        (depth if name.startswith("depth.") else rest).append(p)
    return torch.optim.AdamW([
        {"params": rest, "lr": lr},
        {"params": depth, "lr": lr * depth_lr_mult},
    ])


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--shard", type=Path, required=True, nargs="+",
                   help="one or more .pt shards (shell glob ok)")
    p.add_argument("--steps", type=int, default=2000)
    p.add_argument("--out", type=Path, default=Path("checkpoints/run"))
    p.add_argument("--eval-every", type=int, default=500)
    p.add_argument("--resume", type=Path, default=None,
                   help="checkpoint of trainable weights to resume from")
    p.add_argument("--depth-frac", type=float, default=None,
                   help="override cfg.depth_loss_frame_frac (e.g. 0.25)")
    p.add_argument("--depth-lr-mult", type=float, default=1.0,
                   help="depth decoder LR multiplier (PersonaPlex used 2x)")
    a = p.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)

    cfg = GemmaCSMConfig()
    if a.depth_frac is not None:
        cfg.depth_loss_frame_frac = a.depth_frac
    model, tok = load_gemma_csm(cfg)
    if a.resume:
        sd = torch.load(a.resume, weights_only=True, map_location="cuda")
        missing, unexpected = model.load_state_dict(sd, strict=False)
        assert not unexpected, f"unexpected keys: {unexpected[:5]}"
        print(f"resumed trainables from {a.resume}", flush=True)
    codec = MimiCodec(device="cpu")  # decode for eval on CPU, keep VRAM clean
    ds = CodesDataset(a.shard, tok, max_frames=cfg.max_frames)
    print(f"dataset: {len(ds)} clips")
    dl = DataLoader(ds, batch_size=cfg.batch_size, shuffle=True,
                    collate_fn=lambda b: collate(b, tok.pad_token_id or 0))
    opt = make_optimizer(model, cfg.lr, a.depth_lr_mult)

    step, t0 = 0, time.time()
    while step < a.steps:
        for batch in dl:
            batch = {k: v.cuda() for k, v in batch.items()}
            out = model(batch)
            (out["loss"] / cfg.grad_accum).backward()
            if (step + 1) % cfg.grad_accum == 0:
                opt.step()
                opt.zero_grad()
            if step % 50 == 0:
                print(f"step {step}  c0 {out['loss_c0']:.3f}  "
                      f"depth {out['loss_depth']:.3f}  "
                      f"{(time.time() - t0) / max(step, 1):.2f}s/step", flush=True)
            step += 1
            if step % a.eval_every == 0 or step >= a.steps:
                save_samples(model, tok, codec, a.out / "samples", step)
                torch.save(trainable_state_dict(model), a.out / f"ckpt_{step}.pt")
            if step >= a.steps:
                break
    print("done", flush=True)


if __name__ == "__main__":
    main()
